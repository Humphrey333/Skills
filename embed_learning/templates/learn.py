#!/usr/bin/env python3
"""Learning-path exam runner for @TOPIC_TITLE@ (@TOPIC_SLUG@).

    python3 learn.py            open the first day not yet passed, in the default browser
    python3 learn.py <day>      open that day, unless it is locked
    python3 learn.py status     print progress

The exam page is served on 127.0.0.1 only. Answers stay in .learn/bank_day<N>.json
and never reach the page. A day is passed only at 100%; retakes draw the questions
shown least often. Generated by the embed_learning skill; formats are defined in its
references/bank-format.md and references/notes-format.md.
"""

import argparse
import datetime
import json
import random
import re
import secrets
import shutil
import sys
import time
import webbrowser
from collections import Counter
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

TOPIC_SLUG = "@TOPIC_SLUG@"
TOPIC_TITLE = "@TOPIC_TITLE@"

SECTIONS = ("basic", "medium", "traps")
LETTERS = ("A", "B", "C", "D")
MAX_LONGEST_PERCENT = 40   # a bank where the right option is longest more often than this is a giveaway
LETTER_IN_WHY = re.compile(r"\b(?:[A-D]:|[A-D] (?:is|are|was)\b|[Oo]ption [A-D]\b)")
UNANSWERED = "—"
TIMEOUT_S = 2 * 60 * 60   # stop waiting for a submission after 2 hours
MAX_BODY = 64 * 1024      # a 10-question submission is well under 1 KiB
TABLE_HEADER = "| Day | Status | Attempts | Last score | Weak points (source location) |"


class LearnError(Exception):
    """A problem the developer must fix in the topic folder; printed without a traceback."""


# --- Topic files -------------------------------------------------------------

def learn_dir(root):
    return root / ".learn"


def load_banks(root):
    banks = {}
    for path in sorted(learn_dir(root).glob("bank_day*.json")):
        m = re.fullmatch(r"bank_day(\d+)\.json", path.name)
        if not m:
            continue
        try:
            bank = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            raise LearnError(f"{path.name}: not valid JSON ({e})")
        validate_bank(bank, int(m.group(1)), path.name)
        banks[bank["day"]] = bank
    if not banks:
        raise LearnError(f"no bank_day<N>.json files in {learn_dir(root)}")
    if sorted(banks) != list(range(1, len(banks) + 1)):
        raise LearnError(f"bank days must run 1..N with no gaps, found {sorted(banks)}")
    return banks


def validate_bank(bank, day, name):
    def fail(why):
        raise LearnError(f"{name}: {why}")

    if not isinstance(bank, dict) or bank.get("day") != day:
        fail(f'"day" must be {day}')
    if not isinstance(bank.get("title"), str) or not bank["title"].strip():
        fail('"title" is missing')
    draw = bank.get("draw")
    if (not isinstance(draw, dict) or set(draw) != set(SECTIONS)
            or not all(isinstance(draw[s], int) and draw[s] >= 0 for s in SECTIONS)
            or sum(draw.values()) == 0):
        fail('"draw" needs a count >= 0 for basic, medium and traps, not all zero')
    questions = bank.get("questions")
    if not isinstance(questions, list) or not questions:
        fail('"questions" is missing or empty')

    seen = set()
    per_section = Counter()
    longest = 0
    for i, q in enumerate(questions, 1):
        if not isinstance(q, dict):
            fail(f"question {i} is not an object")
        where = f"question {i} ({q.get('id', 'no id')})"
        for field in ("id", "section", "question", "answer", "source", "why"):
            if not isinstance(q.get(field), str) or not q[field].strip():
                fail(f'{where}: "{field}" is missing or empty')
        if q["id"] in seen:
            fail(f'{where}: duplicate id')
        seen.add(q["id"])
        if q["section"] not in SECTIONS:
            fail(f'{where}: section must be one of {", ".join(SECTIONS)}')
        options = q.get("options")
        if (not isinstance(options, dict) or set(options) != set(LETTERS)
                or not all(isinstance(v, str) and v.strip() for v in options.values())):
            fail(f'{where}: "options" needs non-empty A, B, C and D')
        if q["answer"] not in LETTERS:
            fail(f'{where}: "answer" must be one of A-D')
        if "code" in q and not (isinstance(q["code"], str) and q["code"].strip()):
            fail(f'{where}: "code" must be non-empty text')
        if LETTER_IN_WHY.search(q["why"]):
            fail(f'{where}: "why" names an option by letter; the page shuffles letters, so name it by its text (a plain "C is" about the language trips this too: reword it)')
        lengths = sorted(len(v) for v in options.values())
        if len(options[q["answer"]]) == lengths[-1] and lengths[-1] > lengths[-2]:
            longest += 1
        per_section[q["section"]] += 1
    for s in SECTIONS:
        if per_section[s] < draw[s]:
            fail(f"{s}: draw asks for {draw[s]} questions but the bank has {per_section[s]}")
    if longest * 100 > MAX_LONGEST_PERCENT * len(questions):
        fail(f"the right answer is the strictly longest option in {longest} of {len(questions)} questions "
             f"(limit {MAX_LONGEST_PERCENT}%); rewrite the distractors to match its length")


def read_attempts(root):
    path = learn_dir(root) / "attempts.jsonl"
    if not path.exists():
        return []
    attempts = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.strip():
            try:
                attempts.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise LearnError(f"attempts.jsonl line {n}: not valid JSON ({e})")
    return attempts


def append_attempt(root, record):
    with open(learn_dir(root) / "attempts.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")


# --- Progress ----------------------------------------------------------------

def planned_days(root):
    """Days listed in the Progress.md table, so days whose bank isn't written yet stay visible."""
    path = root / "Progress.md"
    if not path.exists():
        return 0
    days = [int(m.group(1)) for m in re.finditer(r"^\| *(\d+) *\|", path.read_text(encoding="utf-8"), re.M)]
    return max(days, default=0)


def day_rows(banks, attempts, total=0):
    """One row per day. The first day not passed is open; every day after it is locked.

    A planned day with no bank yet is "not ready" when it is the open day, else "locked".
    """
    rows = []
    blocked = False
    for day in range(1, max(total, len(banks)) + 1):
        if day not in banks:
            rows.append({"day": day, "title": None, "status": "locked" if blocked else "not ready",
                         "attempts": 0, "last": "—", "weak": "—"})
            blocked = True
            continue
        tries = [a for a in attempts if a.get("day") == day]
        passed = any(a.get("passed") for a in tries)
        if passed:
            status = "passed"
        elif blocked:
            status = "locked"
        else:
            status = "not passed"
        if not passed:
            blocked = True
        last = tries[-1] if tries else None
        by_id = {q["id"]: q for q in banks[day]["questions"]}
        weak = []
        if last:
            for qid in last.get("wrong", []):
                src = by_id[qid]["source"] if qid in by_id else qid
                if src not in weak:
                    weak.append(src)
        rows.append({
            "day": day,
            "title": banks[day]["title"],
            "status": status,
            "attempts": len(tries),
            "last": f'{last["score"]}/{last["total"]}' if last else "—",
            "weak": "; ".join(weak) if weak else "—",
        })
    return rows


def open_day(rows):
    return next((r["day"] for r in rows if r["status"] == "not passed"), None)


def where_next(rows):
    """What to tell the developer when no day is open."""
    waiting = next((r["day"] for r in rows if r["status"] == "not ready"), None)
    if waiting:
        return f"Day {waiting} has no exam yet. Ask Claude to write its bank and note once its source is supplied."
    return f"All {len(rows)} days are passed."


def topic_rows(root, banks, attempts):
    return day_rows(banks, attempts, planned_days(root))


def progress_table(rows):
    lines = [TABLE_HEADER, "|---|---|---|---|---|"]
    lines += [f'| {r["day"]} | {r["status"]} | {r["attempts"]} | {r["last"]} | {r["weak"]} |' for r in rows]
    return "\n".join(lines) + "\n"


def write_progress(root, banks, attempts):
    """Rewrite only the table; keep every line above and below it as it is."""
    path = root / "Progress.md"
    head, tail = f"# Progress — {TOPIC_SLUG}\n\n", ""
    if path.exists():
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        start = next((i for i, l in enumerate(lines) if l.startswith("| Day |")), None)
        if start is None:
            head = "".join(lines).rstrip("\n") + "\n\n"
        else:
            end = start
            while end < len(lines) and lines[end].startswith("|"):
                end += 1
            head, tail = "".join(lines[:start]), "".join(lines[end:])
    tmp = path.with_suffix(".md.tmp")
    tmp.write_text(head + progress_table(topic_rows(root, banks, attempts)) + tail, encoding="utf-8")
    tmp.replace(path)


# --- One attempt -------------------------------------------------------------

def draw_questions(bank, attempts, rng):
    shown = Counter(qid for a in attempts if a.get("day") == bank["day"] for qid in a.get("shown", []))
    picked = []
    for section in SECTIONS:
        pool = [q for q in bank["questions"] if q["section"] == section]
        rng.shuffle(pool)                        # random order among equally-shown questions...
        pool.sort(key=lambda q: shown[q["id"]])  # ...because sort is stable
        chosen = pool[:bank["draw"][section]]
        rng.shuffle(chosen)
        picked += chosen
    return picked


def shuffle_options(picked, rng):
    """Per question, the bank letters in the order the page shows them as A-D.

    Banks tend to put the right option at the same letter; shuffling per attempt
    stops letter guessing and letter memorizing across retakes.
    """
    orders = []
    for _ in picked:
        order = list(LETTERS)
        rng.shuffle(order)
        orders.append("".join(order))
    return orders


def page_payload(bank, picked, attempt, orders):
    """Everything the page may see. Never ids, keys, sources or explanations."""
    return {
        "topic": TOPIC_TITLE,
        "day": bank["day"],
        "title": bank["title"],
        "attempt": attempt,
        "questions": [
            {"n": f"Q{i}", "section": q["section"], "text": q["question"],
             "options": {page: q["options"][bank] for page, bank in zip(LETTERS, order)},
             **({"code": q["code"]} if "code" in q else {})}
            for i, (q, order) in enumerate(zip(picked, orders), 1)
        ],
    }


def is_pass(score, total):
    return score == total   # the day gate: 100% only


def grade(picked, posted, orders):
    """Map each page letter back to the bank's letter, then compare with the bank."""
    given, wrong = {}, []
    for i, (q, order) in enumerate(zip(picked, orders), 1):
        pick = posted.get(f"Q{i}")
        pick = order[LETTERS.index(pick)] if pick in LETTERS else UNANSWERED
        given[q["id"]] = pick
        if pick != q["answer"]:
            wrong.append(q["id"])
    return given, wrong, len(picked) - len(wrong)


def note_name(bank):
    slug = re.sub(r"[^a-z0-9]+", "-", bank["title"].lower()).strip("-")[:40].strip("-")
    return f'Day{bank["day"]}_{slug}.md'


def release_note(root, bank):
    src = learn_dir(root) / "notes" / f'day{bank["day"]}.md'
    if not src.exists():
        return None
    dst = root / "Notes" / note_name(bank)
    dst.parent.mkdir(exist_ok=True)
    shutil.copyfile(src, dst)
    return dst


# --- Local server ------------------------------------------------------------

class ExamServer(HTTPServer):
    def __init__(self, page, payload, token):
        super().__init__(("127.0.0.1", 0), ExamHandler)
        self.page = page.encode("utf-8")
        self.payload = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.token = token
        self.posted = None


class ExamHandler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def _token_ok(self):
        sent = parse_qs(urlparse(self.path).query).get("t", [""])[0]
        return secrets.compare_digest(sent, self.server.token)

    def _send(self, code, body, ctype="text/plain; charset=utf-8"):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if not self._token_ok():
            return self._send(403, b"Forbidden")
        path = urlparse(self.path).path
        if path == "/":
            return self._send(200, self.server.page, "text/html; charset=utf-8")
        if path == "/exam.json":
            return self._send(200, self.server.payload, "application/json")
        self._send(404, b"Not found")

    def do_POST(self):
        if urlparse(self.path).path != "/submit":
            return self._send(404, b"Not found")
        if not self._token_ok():
            return self._send(403, b"Forbidden")
        if self.server.posted is not None:
            return self._send(409, b"Already submitted")
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            length = -1
        if not 0 < length <= MAX_BODY:
            return self._send(400, b"Bad length")
        try:
            data = json.loads(self.rfile.read(length))
        except (json.JSONDecodeError, UnicodeDecodeError):
            data = None
        if not isinstance(data, dict):
            return self._send(400, b"Expected a JSON object")
        self.server.posted = {str(k): str(v) for k, v in data.items()}
        self._send(200, b'{"ok": true}', "application/json")


def serve(page, payload, open_browser=True, on_ready=None, timeout_s=TIMEOUT_S):
    """Serve one exam and return the posted picks, or None after the timeout."""
    token = secrets.token_urlsafe(16)
    server = ExamServer(page, payload, token)
    server.timeout = 1.0
    url = f"http://127.0.0.1:{server.server_address[1]}/?t={token}"
    print(f"Exam page: {url}", flush=True)
    print("Waiting for your submission (Ctrl+C to stop)...", flush=True)
    if on_ready:
        on_ready(url)
    if open_browser and not webbrowser.open(url):
        print("Could not open a browser. Open the URL above yourself.")
    deadline = time.monotonic() + timeout_s
    try:
        while server.posted is None and time.monotonic() < deadline:
            server.handle_request()
    finally:
        server.server_close()
    return server.posted


def run_day(root, day=None, open_browser=True, rng=None, on_ready=None, timeout_s=TIMEOUT_S):
    """Run one attempt. Returns the attempt record, or None if nothing was submitted."""
    banks = load_banks(root)
    attempts = read_attempts(root)
    rows = topic_rows(root, banks, attempts)
    current = open_day(rows)
    if day is None:
        if current is None:
            print(where_next(rows))
            return None
        day = current
    if not 1 <= day <= len(rows):
        raise LearnError(f"there is no Day {day}; the path has {len(rows)} days")
    status = rows[day - 1]["status"]
    if status == "not ready":
        raise LearnError(where_next(rows))
    if status == "locked":
        raise LearnError(f"Day {day} is locked. Pass Day {current} first: python3 learn.py")
    if status == "passed":
        raise LearnError(f"Day {day} is already passed. Ask Claude for a review exam instead.")

    bank = banks[day]
    attempt = sum(1 for a in attempts if a.get("day") == day) + 1
    rng = rng or random.Random()
    picked = draw_questions(bank, attempts, rng)
    orders = shuffle_options(picked, rng)
    page = (learn_dir(root) / "exam.html").read_text(encoding="utf-8")
    print(f'Day {day}: {bank["title"]} (attempt {attempt}, {len(picked)} questions)')
    posted = serve(page, page_payload(bank, picked, attempt, orders), open_browser, on_ready, timeout_s)
    if posted is None:
        print("No submission arrived; nothing was recorded.")
        return None

    given, wrong, score = grade(picked, posted, orders)
    record = {
        "time": datetime.datetime.now().isoformat(timespec="seconds"),
        "day": day, "attempt": attempt,
        "shown": [q["id"] for q in picked], "order": dict(zip((q["id"] for q in picked), orders)),
        "answers": given, "wrong": wrong,
        "score": score, "total": len(picked), "passed": is_pass(score, len(picked)),
    }
    append_attempt(root, record)
    attempts.append(record)
    write_progress(root, banks, attempts)
    report(root, bank, picked, record, banks, attempts)
    return record


def report(root, bank, picked, record, banks, attempts):
    day, score, total = record["day"], record["score"], record["total"]
    if record["passed"]:
        print(f"\nDay {day} passed ({score}/{total}).")
        note = release_note(root, bank)
        print(f"Lesson note: {note.relative_to(root)}" if note else
              f"No lesson note found at .learn/notes/day{day}.md")
        rows = topic_rows(root, banks, attempts)
        nxt = open_day(rows)
        print(f"Day {nxt} is open: python3 learn.py" if nxt else where_next(rows))
        return
    print(f"\nDay {day}: {score}/{total}, not passed. The pass mark is 100%.")
    print("Re-read these before the retake:")
    for i, q in enumerate(picked, 1):
        if q["id"] in record["wrong"]:
            pick = record["answers"][q["id"]]
            picked_text = q["options"][pick] if pick in LETTERS else "nothing"
            print(f'  Q{i}. {q["question"]}')
            print(f'       you picked: {picked_text}')
            print(f'       re-read: {q["source"]}')
    print("Retake (new questions come first): python3 learn.py")
    print(f'Or ask Claude: "re-teach my last learn.py attempt for Day {day}".')


def print_status(root):
    banks = load_banks(root)
    rows = topic_rows(root, banks, read_attempts(root))
    print(progress_table(rows), end="")
    current = open_day(rows)
    print(f"\nNext: Day {current}: {banks[current]['title']}" if current else "\n" + where_next(rows))


def main(argv=None):
    parser = argparse.ArgumentParser(description=f"Exams for {TOPIC_TITLE}.")
    parser.add_argument("target", nargs="?", default=None,
                        help="'status', or a day number (default: the first day not passed)")
    parser.add_argument("--no-browser", action="store_true", help="print the URL only")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parent
    try:
        if args.target == "status":
            print_status(root)
            return 0
        day = None
        if args.target is not None:
            if not args.target.isdigit():
                parser.error("target must be 'status' or a day number")
            day = int(args.target)
        while True:
            record = run_day(root, day, open_browser=not args.no_browser)
            if not (record and record["passed"]) or args.no_browser or not sys.stdin.isatty():
                return 0
            banks = load_banks(root)
            if open_day(topic_rows(root, banks, read_attempts(root))) is None:
                return 0
            if input("Start the next day now? [y/N] ").strip().lower() != "y":
                return 0
            day = None
    except LearnError as e:
        print(f"learn.py: {e}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("\nStopped; nothing was recorded for this attempt.")
        return 130


if __name__ == "__main__":
    sys.exit(main())
